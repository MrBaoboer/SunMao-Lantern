/**
 * §3 模数与尺寸体系 —— 全项目唯一基准
 *
 * 基本模数 a = 12 mm。原文档保证「所有尺寸必须为 a 的整数倍或 a/12 的整数倍」，
 * 因此取 a/12 = 1 mm 作为内部计算单位，全部几何坐标均为**整数毫米**，
 * 从根本上消除浮点误差 —— 这是能对几何闭合做精确断言的前提。
 *
 * 世界单位 = 毫米。
 */

/** 基本模数 a（毫米） */
export const A = 12;

/**
 * 模数换算：a(1.5) → 18 mm。
 * 传入的分数必须是 1/12 的整数倍，否则抛错（这本身就是一道校验）。
 */
export function a(n = 1) {
  const mm = n * A;
  const r = Math.round(mm);
  if (Math.abs(mm - r) > 1e-9) {
    throw new Error(`模数越界：${n}a = ${mm} mm 不是 a/12（1 mm）的整数倍`);
  }
  return r;
}

/**
 * 自由布局用的模数换算 —— **不做栅格断言**。
 * 仅用于陈列位、镜头距离、幻影尺寸等非结构尺寸；
 * 任何进入构件几何的尺寸必须走 a()，让守卫替你把关。
 */
export function av(n) {
  return Math.round(n * A);
}

/** 双写显示：8a（96 mm）—— §12.5 排版纪律要求全部尺寸标注双写 */
export function dim(n) {
  const frac = fractionLabel(n);
  return `${frac}a（${a(n)} mm）`;
}

function fractionLabel(n) {
  const twelfths = Math.round(n * 12);
  if (twelfths % 12 === 0) return String(twelfths / 12);
  const g = gcd(Math.abs(twelfths), 12);
  const num = twelfths / g;
  const den = 12 / g;
  const whole = Math.trunc(num / den);
  const rem = num - whole * den;
  if (whole !== 0 && rem !== 0) return `${whole}+${rem}/${den}`;
  return `${num}/${den}`;
}
function gcd(x, y) { return y === 0 ? x : gcd(y, x % y); }

