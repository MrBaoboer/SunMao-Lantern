const BY_ID = new Map(MODULE_VO.map((v) => [v.id, v]));

/** 播放某段模块旁白。谜面按题号取，其余按编号取 */
export function playVO(ctx, id) {
  const v = BY_ID.get(id);
  if (v) ctx.voice.play(v.id, v.text, { cps: v.cps });
}
